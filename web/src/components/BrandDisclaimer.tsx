/**
 * 风险提示（免责声明）—— **全站唯一一处展示位**：顶栏站名下方、副标题同一行。
 *
 * ## 为什么挂在顶栏而不是每个一级页签里
 *
 * 用户口径 2026-09-28：「前端大量一级页签下有 disclaimer compact 这个提示块，
 * 这个做到 brand-sub 里就行，删除每个页签下的显示」。
 * 本轮追加口径：「这两个内容要写在一起 …… brand 设置的宽度大一点，
 * 目标是让里面的 brand-sub 争取一行搞定，最多两行」——
 * 所以它与副标题之间只隔一个「 · 」（写在 `App.tsx`），
 * 两段是**同一段文字流**：宽屏一行，≤1366px 折成两行（见 styles.css）。
 *
 * 原文案是用户口语定稿的：「本工具仅供参考学习研究，投资有风险，
 * 非指导建议，盈亏自负」。这类文本**改一个字都要全体一致** ——
 * 各面板各抄一份，迟早出现"某个页面写的是旧版"，而免责声明出现版本不一致
 * 本身就是合规瑕疵。所以文案只在这里定义一次（`DISCLAIMER_TEXT`），
 * 任何地方要用都从这里取。
 *
 * ## 与旧版的差别（别再退回"每页一份"）
 *
 * 旧版是一个 `<Disclaimer compact />` 组件，被挂在 5 个面板内部
 * （做T、资金流、主线挖掘、板块拥挤度、权重编辑器）。带来的问题：
 *   1. **覆盖率必然漏**：每加一个页签就得记得再挂一次，漏挂一个就是
 *      "有信号/有价位却没有风险提示"（2026-09-23 合规自查就是这么发现的）；
 *   2. **页面里多一条常驻噪声**：它出现在每个页签内容区顶部/底部，
 *      用户每切一次页签就被重复念一遍同一句话。
 * 收进顶栏之后：**一次展示、全页签生效**，不存在漏挂；也不再随页签切换重复。
 *
 * ## 为什么在手机上不显示
 *
 * `@media (max-width: 720px)` 里 `.brand-sub` 整块 `display: none`
 * （手机上顶栏高度宝贵），所以本元素随之隐藏 —— 这是既有的、刻意的行为。
 * 桌面端（非手机移动端）才是它的展示位。
 *
 * ## 样式上的两个约束（改了会出事）
 *
 *   · 它必须是 `.brand-sub` 的**子元素**（不能做兄弟节点），否则手机端
 *     不会跟着 `.brand-sub` 一起隐藏；
 *   · 它必须是**行内**元素（`display: inline`，没有 `max-width`）：
 *     做成块级/定宽就会退回"单独一行、必然折两行"，与"写在一起"矛盾。
 */
export const DISCLAIMER_TEXT =
  "本工具仅供参考学习研究，投资有风险，非指导建议，盈亏自负";

/** 顶栏站名下的风险提示行。`title` 让鼠标悬停也能读到全文。 */
export default function BrandDisclaimer() {
  return (
    <span className="brand-disclaimer" title={DISCLAIMER_TEXT}>
      {DISCLAIMER_TEXT}
    </span>
  );
}
