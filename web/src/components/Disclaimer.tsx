/**
 * 风险提示（免责声明）—— **统一一处文案，处处引用**。
 *
 * ## 为什么要做成组件而不是各处再抄一遍
 *
 * 原文案是用户口语定稿的：「本工具仅供参考学习研究，投资有风险，
 * 非指导建议，盈亏自负」。这类文本**改一个字都要全体一致** ——
 * 各面板各抄一份，迟早出现"某个页面写的是旧版"，而免责声明出现版本不一致
 * 本身就是合规瑕疵。
 *
 * ## 为什么这批要"补覆盖"
 *
 * 2026-09-23 合规自查发现：免责声明原来只挂在**量化交易页签右侧**、
 * 日K面板底部、ETF 面板脚注、告警详情、策略案例页 —— 而
 * **做T分时口径（默认视图）、资金流监控、板块拥挤度、主线挖掘、个股口径编辑**
 * 这五个页面有信号/价位/评分，却一条风险提示都没有。
 * 凡是出现"可执行价位"或"信号"的地方都应有显著提示，这是本批的判据。
 *
 * `compact` 用于面板内嵌（更小更淡）；默认样式用于页面级。
 */
export default function Disclaimer({ compact = false }: { compact?: boolean }) {
  return (
    <p className={compact ? "disclaimer compact" : "disclaimer"}>
      本工具仅供参考学习研究，投资有风险，非指导建议，盈亏自负
    </p>
  );
}
