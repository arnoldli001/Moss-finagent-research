"""市场口径常量 —— **只放跨模块共享、且含义不直观的值**。

## 收录标准（避免变成杂物间）

一条值进这里，必须满足**至少两条**：

1. 在 ≥2 个模块出现（重复即漂移风险）；
2. 数值本身不直观（`9.8` 不写名字没人知道是"涨停开盘判定"）；
3. 需要按市场/板块分档（主板 10%、创业板 20%）；
4. 改它会影响多个模块的行为。

**不收**：一次性的局部量（`x / 2`）、只在单文件用的私有常量（就地写更清楚，
读者不用跳文件）、测试数据。后者硬搬进来只会让"这个数字在哪"更难找。

## 口径出处

| 常量 | 出处 |
|---|---|
| 涨跌停幅度 10% / 20% / 5% | 交易所规则；ST 股 5% |
| 涨停开盘判定 9.8% / 19.8% | 留 0.2pct 容差应对四舍五入（涨停价按分取整） |
| 最小流通市值 25 亿 | 涨停次日统计脚本的样本口径（**不是选股门槛**，别混用） |
"""

