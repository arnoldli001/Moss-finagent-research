#: Agent 前缀 → 角色（与 `unlock_teaching._AGENT_ROLE` **保持同一套角色名**）
_AGENT_ROLE: dict[str, str] = {
    "A08": "macro", "A09": "meso", "A10": "micro", "A11": "risk",
    "A12": "compliance",
    "A13": "industry", "A14": "industry", "A15": "industry", "A16": "industry",
    # ★ A20 是兜底行业 Agent，角色与 A13-A16 同为 industry（它要服务任意行业，
    #   教学块里的 "{本行业}" 由它按请求解析出的行业名代入）。
    "A20": "industry",
}


def role_for(agent_id: str) -> str:
    """按 agent_id 前缀取角色（未知返回 'macro' 兜底）。"""
    return _AGENT_ROLE.get(str(agent_id)[:3], "macro")


def render_platform_data_teaching(agent_id: str) -> str:
    """渲染该 Agent 的平台数据教学块（追加到 system_prompt / _requirements）。

    Args:
        agent_id: 如 `A10_micro`

    Returns:
        可直接拼进 prompt 的字符串（以 `\\n\\n` 开头，便于拼接）
    """
    role = role_for(agent_id)
    return "\n\n" + _COMMON_RULES + "\n" + _ROLE_BLOCKS.get(role, _ROLE_BLOCKS["macro"])


