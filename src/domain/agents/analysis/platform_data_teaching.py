"""平台自有后端数据的**共享教学块**（八族：个股五 + 行业三）。

## 为什么需要它（AGENTS.md 里那条"最后一层"）

`AGENTS.md`《本地数据确定性流水线硬约束》写着：

> 「同一缺陷会在多层重复出现，改完一层必须问『还有哪一层会把它吃掉』。」
> 四层里最后一层是 **prompt**：*数据进得了上下文，但 Agent 的 `system_prompt`
> 从没提过它 ⇒ 模型不知道那是信号*。

2026-09-29 实测（本仓真实状态）：`PlatformDataConnector` 的八族数据**已经进了计划、
进了采集、过了白名单**，但 A09/A10/A11/A13–A16/A20 的 prompt 里
**一个字都没提** `估值水位` / `概念拥挤度` / `行业拥挤度` / `板块资金流` / `行业轮动` /
`主线告警` / `个股告警` / `解禁计划` —— 于是模型看到 `- 行业拥挤度:银行 2026-09-24=0.257`
只会当成一行陌生文本。

## 为什么是共享块，不是每个 Agent 各写一段

与 `unlock_teaching.py` **同一个理由**：8 个 Agent 各写一段 = 8 份会各自漂移的文案
（AGENTS.md：「同一个 key 写在 N 处，必有一处被漏改」）。
所以：**共享块 + 角色参数**，每个 Agent 只声明"我是谁、我关心什么"。

## 口径纪律（每一条对应一个已付代价的缺陷）

1. **有数据必须引用**：这几族是**平台自己算出来的**（比新闻硬），
   判"当下/近期行情"时不许只讲新闻不引它们；
2. **没有数据就声明缺口**：不许用训练记忆或估算补 —— 宁可不提；
3. **口径随数据下发**：`extra.basis` / `history_gap` / `is_stale` 里写着
   "这个数字是怎么来的、准不准"（当日截面 vs 近 N 日序列、报告落伍几天、
   含不含同业对标）—— **引用数值时必须同时说清口径**，否则用户会把估算当读数；
4. **"没量到"不是 0**：`value=None` 或整族不产点时如实说"没量到"，
   不许写成 0、也不许写成"该板块资金流为 0"。
"""

