"""解禁信号的**共享教学块**（所有消费 `cal:unlock:*` 的 Agent 共用）。

## 为什么抽成共享模块（本轮最重要的结构性修正）

用户批评（2026-09-28）：
> 「你没有按照你的 skill 经验做事，① 修改点还是类，在开发前你没考虑，
>   所以一个问题（A11 还没教给他 prompt 怎么用）解决前后，
>   没有考虑一类问题（A12/A13-A16 还没教给他 prompt 怎么用）」

**实测证据**：白名单含 `cal:` 的 Agent 共 **9 个**，而我上一轮只教了 **A11**
—— 剩下 8 个的 prompt 里一个字都没提解禁，数据在上下文里但模型不知道那是信号。

## 为什么不能每个 Agent 各写一段

8 个 Agent 各写一段 = **8 份会各自漂移的文案**。
本项目已有教训（AGENTS.md）：
「同一个 key 写在 N 处，必有一处被漏改」。

所以：**共享块 + 角色参数**。每个 Agent 只声明"我是谁、我关心什么"，
文案由本模块统一渲染。

## 每个角色的教学重点（业务口径，不是技术措辞）

| 角色 | 解禁对它的意义 | 教学重点 |
|---|---|---|
| `macro` | 全市场解禁 = 资金面供给压力 | 引用合计规模，作为流动性输入之一 |
| `meso` | 板块级资金分流 | 与板块资金流结合；**不得**声称"本行业解禁"（数据无行业标签） |
| `micro` | 个股供给/估值压力 | 引用 `top_stocks` 的占流通市值比 |
| `risk` | 潜在减持压力（财务风险） | 已由 A11 单独实现（更详细），此处为兜底 |
| `compliance` | 减持是解禁的后置事件 | 与减持/质押事件关联 |
| `industry` | 本行业供给冲击 | ⚠️ **数据无行业标签** → 只能报"全市场背景"，禁止归因到本行业 |

## ⚠️ 诚实边界：行业 Agent 的教学为什么是"降级"的

`CalendarEvent.scope.industries` 实测为 **空数组**（`[]`）。
也就是说解禁事件**没有行业标签**，只有 `codes` / `names`。

所以 A13-A16 **无法**判断"这次解禁是不是我这个行业的"。
硬教它们"看你行业的解禁"会引导**幻觉归因** —— 比不教更危险。

**当前口径**：让行业 Agent 报"全市场解禁背景"（背景噪声），
并**显式禁止**它声称"本行业解禁 N 亿"。
要真正支持行业归因，需要把 `codes` 与 `sector_member` 表做 join
（已登记为已知缺口）。
"""
from __future__ import annotations

